import { expect, test } from '@playwright/test'

test('工作站模块、转换历史与需求上传', async ({ page }) => {
  const password = process.env.AI_STUDIO_E2E_PASSWORD
  if (!password) test.skip(true, 'Set AI_STUDIO_E2E_PASSWORD')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page).toHaveTitle('Test Atelier')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await page.getByRole('button', { name: '新建项目' }).first().click()
  await page.getByLabel('项目名称').fill(`工作站-${Date.now()}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await expect(page.getByText('用例总数')).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.waitForTimeout(300)
  await page.screenshot({ path: '/tmp/ai-studio-workstation-home.png' })

  await page.getByRole('button', { name: '分析需求' }).click()
  await expect(page.getByRole('heading', { name: '需求分析' })).toBeVisible()
  await page.getByRole('button', { name: '首页', exact: true }).click()
  await page.getByRole('button', { name: /用例转换.*核对 Excel 与 XMind/ }).click()
  await expect(page.getByRole('heading', { name: '转换设置' })).toBeVisible()
  await page.screenshot({ path: '/tmp/ai-studio-workstation-conversion-start.png' })
  await page.getByRole('textbox', { name: '前置路径' }).fill('项目路径')
  await expect(page.getByText('已保存到项目配置')).toBeVisible()
  const csv = '用例目录,用例名称,用例等级,前置条件,用例步骤,预期结果,是否是冒烟用例\n登录,有效登录,2,账号存在,输入账号,进入首页,\n'
  await page.locator('input[type=file]').setInputFiles({ name: 'cases.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: '转换并预览' }).click()
  await expect(page.getByRole('heading', { name: '用例预览' })).toBeVisible()
  await page.getByRole('tab', { name: '并排对照' }).click()
  await expect(page.getByText('转换前').last()).toBeVisible()
  await page.screenshot({ path: '/tmp/ai-studio-workstation-conversion.png' })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 Excel' }).click()
  expect((await download).suggestedFilename()).toContain('.xlsx')
  await page.getByRole('button', { name: /历史记录/ }).first().click()
  await expect(page.getByRole('button', { name: '查看历史预览' })).toBeVisible()

  await page.getByRole('button', { name: '需求分析' }).first().click()
  await expect(page.getByRole('heading', { name: '需求分析' })).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({ name: 'requirement.md', mimeType: 'text/markdown', buffer: Buffer.from('# 登录\n输入有效账号后进入首页') })
  await expect(page.getByText('提取内容预览')).toBeVisible()
  await page.getByRole('button', { name: '开始分析' }).click()
  await expect(page.getByText('无法连接本地 Ollama')).toBeVisible({ timeout: 15000 })
  await page.screenshot({ path: '/tmp/ai-studio-workstation-analysis.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(page.getByRole('heading', { name: '需求分析' })).toBeVisible()
  await expect(page.getByText('无法连接本地 Ollama')).toBeVisible()
  await page.waitForTimeout(400)
  await expect(page.getByRole('button', { name: '开始分析' })).toBeVisible()
  await page.screenshot({ path: '/tmp/ai-studio-workstation-mobile.png' })
  expect(errors).toEqual([])
})
