import { expect, test } from '@playwright/test'
import path from 'node:path'

test('分派、待我审核、讨论与批量审核', async ({ page }) => {
  const adminPassword = process.env.AI_STUDIO_E2E_PASSWORD
  if (!adminPassword) test.skip(true, 'Set AI_STUDIO_E2E_PASSWORD')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const suffix = Date.now()
  const reviewer = `collab-${suffix}`
  const reviewerPassword = 'reviewer-password-123'

  await page.goto('/')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(adminPassword!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await page.getByRole('button', { name: '新建项目' }).first().click()
  await page.getByLabel('项目名称').fill(`协作验收-${suffix}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByRole('button', { name: '项目成员' }).click()
  await page.getByRole('button', { name: '创建账号' }).click()
  await page.getByLabel('用户名').fill(reviewer)
  await page.getByLabel('初始密码').fill(reviewerPassword)
  await page.getByRole('button', { name: '创建并加入' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '用例库' }).first().click()
  await page.getByRole('button', { name: '导入用例' }).click()
  await page.locator('input[type=file]').setInputFiles(path.resolve(process.env.AI_STUDIO_E2E_SAMPLE || 'e2e/fixtures/UGOS_PRO_sample.xlsx'))
  await expect(page.getByText('100 条用例 · 13 个原始字段')).toBeVisible()
  await page.getByRole('button', { name: '确认导入 100 条' }).click()
  await page.getByText('001252040').first().click()
  await expect(page.getByRole('heading', { name: '新客户端旧套件兼容性' })).toBeVisible()
  await page.getByRole('combobox', { name: '分派负责人' }).click()
  await page.getByRole('option', { name: reviewer }).click()
  await expect(page.getByText(`已分派给 ${reviewer}`)).toBeVisible()
  await page.getByRole('tab', { name: '讨论与记录' }).click()
  await page.getByRole('textbox', { name: '讨论内容' }).fill('请确认兼容场景的预期')
  await page.getByRole('button', { name: '发表' }).click()
  await expect(page.getByText('请确认兼容场景的预期')).toBeVisible()
  expect(await page.locator('.review-tabs [data-slot=tabs-content][data-state=active]').evaluate(element => {
    const pane = element.closest('.pane-scroll')!
    return element.getBoundingClientRect().left - pane.getBoundingClientRect().left < 40
  })).toBe(true)
  await page.screenshot({ path: '/tmp/ai-studio-collab-detail.png' })

  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByLabel('账号').fill(reviewer)
  await page.getByLabel('密码').fill(reviewerPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await expect(page.getByRole('region', { name: '项目概况' }).getByRole('button', { name: /待我审核 1/ })).toBeVisible()
  await page.getByRole('region', { name: '项目概况' }).getByRole('button', { name: /待我审核 1/ }).click()
  await expect(page.getByRole('heading', { name: '用例审核' })).toBeVisible()
  await expect(page.getByText('1 条用例')).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 条用例')).toBeVisible()
  await page.getByText('001252040').first().click()
  await page.getByPlaceholder('说明判断依据或修改原因').fill('核对后保留待判定')
  await page.getByRole('button', { name: '保存审核' }).click()
  await expect(page.getByText('审核已保存')).toBeVisible()
  await page.getByRole('tab', { name: '讨论与记录' }).click()
  await expect(page.getByText('请确认兼容场景的预期')).toBeVisible()
  await expect(page.getByText('核对后保留待判定')).toBeVisible()

  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(adminPassword!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '用例库' }).first().click()
  await page.getByRole('checkbox', { name: '选择用例 001252040' }).check()
  await page.locator('.case-row').nth(1).getByRole('checkbox').check()
  await page.getByRole('button', { name: '批量审核' }).click()
  await page.getByPlaceholder('说明本次审核依据').fill('批量复核原始等级与冒烟值')
  await page.getByRole('button', { name: '逐条提交审核' }).click()
  await expect(page.getByText(/已保存 1 条 · 冲突 0 条/)).toBeVisible()
  await expect(page.getByText('无变化')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/ai-studio-collab-batch-mobile.png' })
  await page.getByRole('button', { name: '完成' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.waitForTimeout(250)
  await page.screenshot({ path: '/tmp/ai-studio-collab-list-mobile.png' })
  expect(errors).toEqual([])
})
