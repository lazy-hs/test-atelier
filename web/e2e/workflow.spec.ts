import { expect, test } from '@playwright/test'
import path from 'node:path'

test('真实样本导入、审核与导出', async ({ page }) => {
  const password = process.env.AI_STUDIO_E2E_PASSWORD
  if (!password) test.skip(true, 'Set AI_STUDIO_E2E_PASSWORD for the local server')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page).toHaveTitle('Test Atelier')
  await expect(page.getByRole('heading', { name: '登录 Test Atelier' })).toBeVisible()
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await page.getByRole('button', { name: '新建项目' }).first().click()
  await page.getByLabel('项目名称').fill(`验收-${Date.now()}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByRole('button', { name: '用例库' }).first().click()
  await expect(page.getByRole('heading', { name: '用例审核' })).toBeVisible()
  await page.locator('header.topbar').getByRole('button', { name: '导入用例' }).click()
  await page.locator('input[type="file"]').setInputFiles(path.resolve(process.env.AI_STUDIO_E2E_SAMPLE || 'e2e/fixtures/UGOS_PRO_sample.xlsx'))
  await expect(page.getByText('100 条用例 · 13 个原始字段')).toBeVisible()
  await page.waitForTimeout(200)
  await page.screenshot({ path: '/tmp/ai-studio-preview.png' })
  await page.getByRole('button', { name: '确认导入 100 条' }).click()
  await expect(page.getByText('100 条用例').first()).toBeVisible()
  await expect(page.getByText('001252040').first()).toBeVisible()
  await page.getByText('001252040').first().click()
  await expect(page.getByRole('heading', { name: '新客户端旧套件兼容性' })).toBeVisible()
  await page.waitForTimeout(300)
  await page.getByPlaceholder('说明判断依据或修改原因').fill('核对原始记录后保留待判定')
  await page.getByRole('button', { name: '保存审核' }).click()
  await expect(page.getByText('审核已保存')).toBeVisible()
  await page.screenshot({ path: '/tmp/ai-studio-desktop.png' })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 Excel' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/project-\d+-cases\.xlsx/)
  await download.saveAs('/tmp/ai-studio-export.xlsx')
  await page.getByRole('button', { name: '首页', exact: true }).click()
  await expect(page.getByRole('region', { name: '项目概况' }).getByRole('button', { name: /用例总数 100/ })).toBeVisible()
  await expect(page.getByRole('region', { name: '项目概况' }).getByRole('button', { name: /待审核 99/ })).toBeVisible()
  await expect(page.locator('.home-activity-row').first()).toContainText('已导入')
  await page.waitForTimeout(350)
  await page.screenshot({ path: '/tmp/ai-studio-home-populated.png' })
  await page.locator('.home-activity-row').first().click()
  await expect(page.getByRole('heading', { name: '导入记录' })).toBeVisible()
  await page.getByRole('button', { name: '首页', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await page.waitForTimeout(350)
  await page.screenshot({ path: '/tmp/ai-studio-home-populated-mobile.png' })
  await page.getByRole('button', { name: '用例库' }).first().click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '用例审核' })).toBeVisible()
  await page.getByText('001252040').first().click()
  await expect(page.getByRole('heading', { name: '新客户端旧套件兼容性' })).toBeVisible()
  await page.screenshot({ path: '/tmp/ai-studio-mobile.png' })
  expect(errors).toEqual([])
})
