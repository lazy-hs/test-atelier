import { expect, test } from '@playwright/test'

test('管理员配置本地与远程模型', async ({ page }) => {
  const password = process.env.AI_STUDIO_E2E_PASSWORD
  if (!password) test.skip(true, 'Set AI_STUDIO_E2E_PASSWORD')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))

  await page.goto('/')
  await page.route('**/ai/admin-config/detect', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ results: [{ ok: true, protocol: 'openai', model: 'test-model', status: 200 }, { ok: false, protocol: 'anthropic', model: 'test-model', status: 401, error: 'unauthorized' }] }) }))
  await page.route('**/ai/admin-config/models', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ models: [{ id: 'test-model', name: 'Test Model' }, { id: 'second-model', name: 'Second Model' }] }) }))
  await page.route('**/ai/admin-config/test-models', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ results: [{ ok: true, protocol: 'openai', model: 'test-model', status: 200 }] }) }))
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  // Model settings are exposed from the project workspace and the API scopes
  // the admin endpoint to a project, so create a disposable project first.
  await page.getByRole('button', { name: '新建项目' }).first().click()
  await page.getByLabel('项目名称').fill(`模型配置-${Date.now()}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByRole('button', { name: '模型配置' }).click()
  await expect(page.getByRole('heading', { name: '模型配置' })).toBeVisible()
  await expect(page.getByText('仅全局管理员可见')).toBeVisible()
  await expect(page.getByRole('button', { name: /Codex CLI/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Claude Code/ })).toHaveCount(0)
  const localProvider = page.locator('.provider-row').filter({ hasText: '本机 Ollama' }).first()
  if (!(await localProvider.getAttribute('class'))?.includes('is-muted')) await localProvider.locator('.provider-switch').click()
  await expect(localProvider).toHaveClass(/is-muted/)
  await page.getByRole('button', { name: '保存配置' }).click()
  await expect(page.getByText('模型配置已保存并立即生效')).toBeVisible()
  await page.getByRole('button', { name: '添加供应商' }).click()
  await expect(page.getByRole('heading', { name: '自定义供应商' })).toBeVisible()
  await page.getByLabel('供应商名称').fill('E2E Relay')
  await page.getByLabel('供应商 Base URL').fill('https://example.com/v1')
  await page.getByRole('textbox', { name: '供应商 API 密钥' }).fill('sk-e2e-secret')
  await page.getByLabel('供应商模型名称').last().fill('test-model')
  await page.getByRole('button', { name: '检测协议' }).click()
  await expect(page.getByText('已检测到协议 openai')).toBeVisible()
  await page.getByRole('button', { name: '获取模型' }).click()
  await expect(page.getByRole('button', { name: /Test Model/ })).toBeVisible()
  await page.getByRole('button', { name: '逐个检测已选模型' }).click()
  await expect(page.getByText('已检测 1 个模型 1 个可用')).toBeVisible()
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await page.getByRole('button', { name: '保存配置' }).click()
  await expect(page.getByText('模型配置已保存并立即生效')).toBeVisible()
  await expect(page.getByText('E2E Relay').first()).toBeVisible()
  await page.getByRole('button', { name: /E2E Relay/ }).first().click()
  await expect(page.getByRole('heading', { name: '编辑供应商' })).toBeVisible()
  await page.getByLabel('供应商名称').fill('E2E Relay Updated')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '保存配置' }).click()
  await expect(page.getByText('模型配置已保存并立即生效')).toBeVisible()
  await page.getByRole('button', { name: /E2E Relay Updated/ }).first().click()
  await expect(page.getByRole('heading', { name: '编辑供应商' })).toBeVisible()
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.getByText('已复制供应商 点击保存配置后生效')).toBeVisible()
  await page.getByRole('button', { name: /E2E Relay Updated 副本/ }).first().click()
  await expect(page.getByRole('heading', { name: '编辑供应商' })).toBeVisible()
  await page.getByRole('button', { name: '移除', exact: true }).click()
  await expect(page.getByText('供应商已移除 点击保存配置后生效')).toBeVisible()
  await page.getByRole('button', { name: '保存配置' }).click()
  await expect(page.getByText('模型配置已保存并立即生效')).toBeVisible()
  await page.getByLabel('选择测试 provider').selectOption('remote')
  await page.getByRole('button', { name: '测试连接' }).click()
  await expect(page.getByText(/无法连接|模型服务无法连接/)).toBeVisible({ timeout: 10000 })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: '模型配置' })).toBeVisible()
  await page.screenshot({ path: '/tmp/test-atelier-model-settings-mobile.png' })
  expect(errors).toEqual([])
})
