import { expect, test } from '@playwright/test'
import path from 'node:path'

test('模型候选只在人工接受后写入最终值', async ({ page }) => {
  if (!process.env.AI_STUDIO_E2E_MODEL_STUB) test.skip(true, 'Run with the local Ollama test stub')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill(process.env.AI_STUDIO_E2E_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '新建项目' }).first().click()
  await page.getByLabel('项目名称').fill(`模型建议-${Date.now()}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByRole('button', { name: '用例库' }).first().click()
  await expect(page.getByRole('heading', { name: '用例审核' })).toBeVisible()
  await page.locator('header.topbar').getByRole('button', { name: '导入用例' }).click()
  await page.locator('input[type=file]').setInputFiles(path.resolve(process.env.AI_STUDIO_E2E_SAMPLE || '/Users/lazy/Downloads/UGOS_PRO_测试用例_20261015141029.xls'))
  await page.getByRole('button', { name: '确认导入 100 条' }).click()
  await page.getByText('001252040').first().click()
  await page.getByRole('tab', { name: '建议' }).click()
  await page.locator('.suggestion-actions').getByRole('button', { name: 'AI 建议' }).click()
  await expect(page.getByText('AI 建议完成')).toBeVisible({ timeout: 15000 })
  await expect(page.getByText('AI 候选', { exact: true })).toBeVisible()
  await expect(page.getByText('模型候选需人工核对')).toBeVisible()
  await page.getByRole('textbox', { name: '建议决策理由' }).fill('人工复核后保留原等级，冒烟待判定')
  await page.getByRole('button', { name: '接受建议' }).click()
  await expect(page.getByRole('combobox', { name: '最终等级' })).toContainText('等级 1')
  await expect(page.getByRole('combobox', { name: '最终冒烟' })).toContainText('待判定')
  await page.getByRole('tab', { name: '建议' }).click()
  await expect(page.getByRole('button', { name: 'AI 候选 已采纳' })).toBeVisible()
  await page.waitForTimeout(300)
  await page.screenshot({ path: '/tmp/ai-studio-model-suggestion-accepted.png' })
  expect(errors).toEqual([])
})
